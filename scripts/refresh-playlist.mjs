// Rebuilds src/features/music/playlist-tracks.ts from Yakob's public Spotify playlist "ethio".
//
// The site's music player plays Spotify's own 30-second preview clips, so it needs each
// song's preview address. Spotify's public embed page lists them (for the first 100 songs
// of a playlist), and no account or API key is needed to read it.
//
// Run it again if songs stop playing or the playlist changes:
//   node scripts/refresh-playlist.mjs

import { writeFile } from "node:fs/promises";

const PLAYLIST_ID = "0a2BKVNn9VVeAMrQz3ngIw";
const EMBED_URL = `https://open.spotify.com/embed/playlist/${PLAYLIST_ID}`;
const OUTPUT_FILE = new URL("../src/features/music/playlist-tracks.ts", import.meta.url);

const response = await fetch(EMBED_URL, {
  headers: { "User-Agent": "Mozilla/5.0" },
  signal: AbortSignal.timeout(20_000),
});
if (!response.ok) throw new Error(`Spotify answered ${response.status} for ${EMBED_URL}`);

const html = await response.text();
const pageData = html.match(/<script id="__NEXT_DATA__" type="application\/json">(.*?)<\/script>/s);
if (!pageData) throw new Error("The embed page no longer contains its track data.");

const playlist = JSON.parse(pageData[1]).props.pageProps.state.data.entity;

const tracks = playlist.trackList
  // Only clips served from Spotify's preview host are used; the site's security policy allows no other.
  .filter((track) => track.audioPreview?.url?.startsWith("https://p.scdn.co/mp3-preview/"))
  .map((track) => ({
    id: track.uri.replace("spotify:track:", ""),
    title: track.title,
    artist: track.subtitle,
    previewUrl: track.audioPreview.url,
  }));

if (tracks.length === 0) throw new Error("No songs with a preview clip were found.");

const today = new Date().toISOString().slice(0, 10);
const lines = tracks.map((track) => `  ${JSON.stringify(track)},`).join("\n");
const file = `// Generated by scripts/refresh-playlist.mjs on ${today}. Do not edit by hand.
// Songs from Yakob's public Spotify playlist "ethio" that have a 30-second preview clip.

export type PlaylistTrack = {
  // Spotify track id, used for the "open in Spotify" link.
  id: string;
  title: string;
  artist: string;
  previewUrl: string;
};

export const PLAYLIST_URL = "https://open.spotify.com/playlist/${PLAYLIST_ID}";

export const playlistTracks: PlaylistTrack[] = [
${lines}
];
`;

await writeFile(OUTPUT_FILE, file);
console.log(`Wrote ${tracks.length} of ${playlist.trackList.length} songs to ${OUTPUT_FILE.pathname}`);
